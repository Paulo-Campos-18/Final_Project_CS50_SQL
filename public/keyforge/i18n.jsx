// Translate. Falls back to en-US, then to the key itself.
const t = (key, vars) => {
  const lang = (window.__lang || "pt-BR");
  const dict = STRINGS[lang] || STRINGS["pt-BR"];
  let s = dict[key];
  if (s == null) s = STRINGS["en-US"][key];
  if (s == null) return key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, vars[k]);
  }
  return s;
};

// Locale-aware date formatter
const fmtDate = (iso, opts = { month: "long", day: "numeric", year: "numeric" }) => {
  const lang = (window.__lang || "pt-BR");
  const locale = lang === "pt-BR" ? "pt-BR" : "en-US";
  return new Date(iso).toLocaleDateString(locale, opts);
};

Object.assign(window, { STRINGS, LANGUAGES, t, fmtDate });
